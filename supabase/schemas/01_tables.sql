-- Accounts: personal finance tracking from uploaded bank statements.
-- Fully admin-only, no self-service scoping (unlike HRMS).
create table public.statement_imports (
    id bigint generated by default as identity primary key,
    filename text not null,
    period_from date,
    period_to date,
    transaction_count integer not null default 0,
    sales_id bigint,
    created_at timestamp with time zone not null default now()
);

create table public.transactions (
    id bigint generated by default as identity primary key,
    date date not null,
    description text not null,
    amount numeric(12,2) not null,
    category text,
    balance_after numeric(12,2),
    source text not null default 'manual',
    statement_import_id bigint,
    notes text,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    -- Personal vs. business, tagged per transaction rather than split into
    -- a separate app/DB -- see docs/accounts-roadmap.md.
    scope text not null default 'business',
    -- Which recurring_expenses row this real transaction was matched
    -- against, if any -- see the recurring_expenses table comment below.
    recurring_expense_id bigint,
    constraint transactions_source_check check (source in ('manual', 'statement')),
    constraint transactions_scope_check check (scope in ('business', 'personal'))
);

-- Unavoidable monthly expenses (EMI, class fees, rent, subscriptions) --
-- see docs/accounts-roadmap.md. match_keyword lets statement import review
-- auto-suggest linking a real imported transaction to one of these, same
-- shape as categoryRules keyword matching (matchCategoryRule) -- set once
-- by the user, not learned automatically from bank statement text.
create table public.recurring_expenses (
    id bigint generated by default as identity primary key,
    name text not null,
    amount numeric(12,2) not null,
    category text,
    scope text not null default 'personal',
    due_day integer not null,
    match_keyword text,
    active boolean not null default true,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint recurring_expenses_scope_check check (scope in ('business', 'personal')),
    constraint recurring_expenses_due_day_check check (due_day between 1 and 28)
);

-- Khatabook-style personal lending ledger -- who I've given money to, who's
-- given money to me. See docs/accounts-roadmap.md: loans.transaction_id
-- links to the real transactions row created alongside a loan (offered,
-- not forced -- a cash loan has nothing to link to), so the bank total and
-- the "who owes me" total can't silently disagree.
create table public.people (
    id bigint generated by default as identity primary key,
    name text not null,
    phone text,
    sales_id bigint,
    created_at timestamp with time zone not null default now()
);

create table public.loans (
    id bigint generated by default as identity primary key,
    person_id bigint not null,
    -- 'given' = I lent them money, they owe me. 'received' = I borrowed
    -- from them, I owe them.
    direction text not null,
    amount numeric(12,2) not null,
    scope text not null default 'personal',
    settled boolean not null default false,
    settled_at timestamp with time zone,
    transaction_id bigint,
    notes text,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    constraint loans_direction_check check (direction in ('given', 'received')),
    constraint loans_scope_check check (scope in ('business', 'personal')),
    constraint loans_amount_check check (amount > 0)
);

-- Actual-vs-budgeted per category per month per scope -- see
-- docs/accounts-roadmap.md. sales_id is audit-trail only (who set it), NOT
-- part of the natural key -- transactions' RLS already means every admin
-- shares one ledger, not a per-admin one.
create table public.budgets (
    id bigint generated by default as identity primary key,
    category text not null,
    scope text not null default 'business',
    month date not null, -- always the 1st of the month
    amount numeric(12,2) not null,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint budgets_scope_check check (scope in ('business', 'personal')),
    constraint budgets_amount_check check (amount > 0),
    unique (category, scope, month)
);

