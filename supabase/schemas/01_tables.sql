-- Leads: staging area for unqualified/raw contact data, separate from
-- contacts/companies. Funnel: new -> contacted -> qualified/disqualified.
-- Qualifying converts a lead into a real Contact (+ Company/Deal) --
-- the lead row is kept as an audit trail via converted_*_id.
create table public.leads (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    company_name text,
    email text,
    phone text,
    title text,
    source text,
    notes text,
    status text not null default 'new',
    disqualify_reason text,
    assignee_id bigint,
    converted_contact_id bigint,
    converted_company_id bigint,
    converted_deal_id bigint,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint leads_status_check check (status in ('new', 'contacted', 'qualified', 'disqualified'))
);

-- Contact-attempt log: every call/WhatsApp/email attempt a rep makes on a
-- lead, whether or not it got a response -- see the leads table comment
-- above. leads.status still tracks the coarse funnel stage; this tracks the
-- actual outreach history behind it. "Last attempt / how many" is computed
-- live from these rows in leads_summary (see 03_views.sql), not
-- denormalized onto leads itself.
create table public.lead_activities (
    id bigint generated by default as identity primary key,
    lead_id bigint not null,
    sales_id bigint,
    channel text not null,
    outcome text,
    created_at timestamp with time zone not null default now(),
    constraint lead_activities_channel_check check (channel in ('call', 'whatsapp', 'email')),
    constraint lead_activities_outcome_check check (
        outcome is null or outcome in ('no_answer', 'responded', 'wrong_number', 'not_interested', 'callback_later')
    )
);

