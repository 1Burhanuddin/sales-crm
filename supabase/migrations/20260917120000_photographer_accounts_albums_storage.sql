-- Per-photographer storage usage, for display on their detail page.
-- security_invoker so RLS on the underlying tables still applies to
-- whoever queries the view -- without it, a photographer-role login
-- would see every photographer's total, not just their own.
create view public.photographer_storage_usage
    with (security_invoker = true) as
select
    ph.id,
    coalesce(sum(gp.size_bytes), 0)::bigint as total_bytes,
    count(gp.id) as photo_count
from public.photographers ph
left join public.photo_galleries pg on pg.photographer_id = ph.id
left join public.gallery_albums ga on ga.gallery_id = pg.id
left join public.gallery_photos gp on gp.album_id = ga.id
group by ph.id;

grant select on public.photographer_storage_usage to authenticated;
grant select on public.photographer_storage_usage to service_role;
revoke all on public.photographer_storage_usage from anon;
